"""The yonga compatibility registry.

Knowledge that changes faster than the code — which architecture runs on which
Intel device, which exporter version it needs, what a known failure looks like,
which repair fixes it — lives here as data. The package has three layers:

* :mod:`yonga.registry.schema` defines the typed records,
* :mod:`yonga.registry.loader` reads and merges YAML layers (``yaml.safe_load``
  only, so registry data can never execute Python),
* :mod:`yonga.registry.resolver` picks rules deterministically and explains why.

Nothing here imports OpenVINO, Optimum, Transformers or Torch, so the registry
can be loaded and validated on any machine.
"""

